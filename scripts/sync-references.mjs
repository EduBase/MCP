#!/usr/bin/env node
/* Regenerate the reference documents served by the MCP server (src/references/*.ts) from the EduBase developer documentation
 * Usage: node scripts/sync-references.mjs <path to the developer documentation repository> */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DOCS = process.argv[2] || process.env.EDUBASE_DEVELOPER_DOCS;
if (!DOCS) {
	console.error('Usage: node scripts/sync-references.mjs <path to the developer documentation repository>');
	process.exit(1);
}
const OUTPUT = fileURLToPath(new URL('../src/references/', import.meta.url));

/* Lines of a page between a start line and the next line matching the end pattern */
function extract(page, start, end) {
	const lines = readFileSync(join(DOCS, 'docs/api/endpoints', page), 'utf-8').split('\n');
	const from = lines.findIndex((line) => line.trim() == start);
	if (from < 0) {
		throw new Error(`"${start}" not found in ${page}`);
	}
	const to = lines.findIndex((line, index) => index > from && end.test(line));
	return lines.slice(from, to < 0 ? undefined : to);
}

/* Convert the MkDocs Material syntax to plain Markdown */
function toMarkdown(lines) {
	const output = [];
	const admonitions = [];
	for (const line of lines) {
		const indent = line.match(/^ */)[0].length;
		if (line.trim().length > 0) {
			/* Admonition contents are indented by 4 spaces more than the admonition */
			while (admonitions.length > 0 && indent < admonitions[admonitions.length - 1] + 4) {
				admonitions.pop();
			}
		}
		const dedented = line.slice(Math.min(indent, admonitions.length * 4));
		const admonition = dedented.match(/^(\s*)(\?\?\?\+?|!!!) [a-z]+(?: "(.*)")?\s*$/);
		if (admonition) {
			admonitions.push(indent);
			if (admonition[3]) {
				output.push(`${admonition[1]}**${admonition[3]}**`, '');
			}
			continue;
		}
		if (/^\[\^\d+\]:/.test(dedented)) {
			continue;
		}
		output.push(dedented
			.replace(/\[:material-[a-z-]+:\] \^\^(.+?)\^\^:/g, '**$1:**')
			.replace(/==\[!\]== /g, '(required) ')
			.replace(/\[\^\d+\]/g, '')
			.replace(/\[([^\]]+)\]\((?!https?:)[^)]*\)/g, '$1'));
	}
	return output.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
}

/* Write a generated module exporting the document */
function write(file, constant, comment, markdown) {
	writeFileSync(join(OUTPUT, file), `/* ${comment} (generated by scripts/sync-references.mjs from the EduBase developer documentation, do not edit) */\nexport const ${constant} = ${JSON.stringify(markdown)};\n`);
	console.log(`${file}: ${markdown.length} characters`);
}

write('questions.ts', 'EDUBASE_REFERENCE_QUESTIONS', 'Question fields, types and formatting', '# EduBase questions reference\n\nFields of edubase_post_question (the API field names), with the question types, formatting, parameters, scoring and the other options. The examples call the API directly: with edubase_post_question, pass the question text in the content field (question in the examples), and leave out app and secret.\n\n' + toMarkdown(extract('questions.md', '### POST /question', /^### /)));
write('exam-journeys.ts', 'EDUBASE_REFERENCE_EXAM_JOURNEYS', 'Portable JSON format of exam journeys', '# EduBase exam journey format\n\nPortable JSON format of the journeys, used by edubase_get_exam_journey_graph and edubase_put_exam_journey_graph.\n\n' + toMarkdown(extract('exams.md', '??? info "Portable JSON Format"', /^### /)).replace(/^\*\*Portable JSON Format\*\*\n\n/, ''));
